"""Permanent external contract: a pure-invalid ``pvsyst_run_simulation`` request
must launch zero PVsystCLI processes and write zero result files.

Driven only through the public stdio MCP server (no internal function-order,
no Mock, no patched ``license_info`` / ``_run``).  Each case runs in its own
throwaway workspace.  "0 launches" is not taken on faith from an inert stub:
``PVSYST_CLI`` is the real ``sys.executable`` and a generated ``sitecustomize``
appends one line per launched console command (argv[0] in
``lic-info``/``help``/``run-simulation``; the MCP server's own argv[0] is the
server script, so it is never counted).  Before every case the guard itself is
fired once with ``python lic-info`` and shown to record a hit, so a later empty
counter proves the request really spawned nothing rather than the guard being
dead.  No PVsyst executable runs and no license is consumed anywhere here.

Error text is the pre-existing preflight contract (``project/paths.py`` /
``native/cli.py`` messages); it is not redefined to suit any implementation.
An unfixed product that runs ``license_info`` before the pure checks regresses
this contract: the counter becomes non-empty even though the message matches.
"""
import asyncio
import os
import shutil
import subprocess
import sys
import tempfile
import unittest
from collections import namedtuple
from pathlib import Path

from mcp import ClientSession
from mcp.client.stdio import StdioServerParameters, stdio_client

REPO = Path(__file__).resolve().parents[2]

# sitecustomize dropped on the server's PYTHONPATH: a real launch counter.
GUARD_SOURCE = (
    "import os, sys\n"
    "try:\n"
    "    _name = os.path.basename(sys.argv[0] or '')\n"
    "    if _name in ('lic-info', 'help', 'run-simulation'):\n"
    "        _t = os.environ.get('PVSYST_GUARD_COUNTER')\n"
    "        if _t:\n"
    "            with open(_t, 'a', encoding='utf-8') as _fh:\n"
    "                _fh.write(_name + '\\n')\n"
    "except Exception:\n"
    "    pass\n"
)

Case = namedtuple("Case", "name request error prebuild")

# Pure-invalid requests: each fails an existing preflight branch before any
# native process is needed. (project/variant exist only as workspace listing
# entries; no content is read for these branches.)
CASES = (
    Case("bad_sfi_suffix",
         {"project": "Example.PRJ", "variant": "VC0", "csv_name": "run", "sfi_name": "notes.txt"},
         "Expected a .sfi filename", None),
    Case("bad_date",
         {"project": "Example.PRJ", "variant": "VC0", "csv_name": "run",
          "start_date": "2024-01-01", "end_date": "2024-01-02"},
         "Date must use MM.DD", None),
    Case("missing_project",
         {"project": "Missing.PRJ", "variant": "VC0", "csv_name": "run"},
         "must exist in the workspace", None),
    Case("missing_variant",
         {"project": "Example.PRJ", "variant": "VC9", "csv_name": "run"},
         "must exist in the workspace", None),
    Case("output_collision",
         {"project": "Example.PRJ", "variant": "VC0", "csv_name": "existing"},
         "Output must be a new .csv file", "existing.csv"),
    Case("no_outputs",
         {"project": "Example.PRJ", "variant": "VC0"},
         "Request a CSV and/or a PDF output", None),
    Case("batch_conflict",
         {"project": "Example.PRJ", "variant": "VC0", "csv_name": "run",
          "batch_params_name": "ScenarioParms.CSV"},
         "Batch output is generated by the CLI", None),
)


def hits(counter: Path):
    if not counter.exists():
        return []
    return [line.strip() for line in counter.read_text(encoding="utf-8").splitlines() if line.strip()]


class RunSimulationPreflightNoLaunchBoundary(unittest.TestCase):
    def test_invalid_requests_spawn_zero_cli_and_write_nothing(self):
        for case in CASES:
            with self.subTest(case=case.name):
                asyncio.run(self._check(case))

    def _child_env(self, guard: Path, workspace: Path, counter: Path) -> dict:
        env = dict(os.environ)
        env["PVSYST_CLI"] = sys.executable
        env["PVSYST_WORKSPACE"] = str(workspace)
        env["PYTHONPATH"] = os.pathsep.join([str(guard), str(REPO / "src")])
        env["PYTHONDONTWRITEBYTECODE"] = "1"
        env["PVSYST_GUARD_COUNTER"] = str(counter)
        env.pop("PVSYST_TOOL_GROUPS", None)
        env.pop("PVSYST_BUILTIN_COMPONENTS", None)
        return env

    def _prove_guard_live(self, env: dict, counter: Path) -> None:
        """One throwaway real launch must be counted before we trust a zero."""
        counter.write_text("", encoding="utf-8")
        subprocess.run([sys.executable, "lic-info"], cwd=str(counter.parent), env=env,
                       stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
                       stderr=subprocess.DEVNULL, timeout=60)
        self.assertEqual(hits(counter), ["lic-info"],
                         "guard did not record a real lic-info launch; a zero count would be unreliable")
        counter.write_text("", encoding="utf-8")

    async def _call(self, env: dict, base: Path, request: dict) -> tuple[bool, str]:
        params = StdioServerParameters(command=sys.executable,
                                       args=[str(REPO / "pvsyst_mcp_server.py")],
                                       cwd=str(base), env=env)
        async with stdio_client(params) as (read, write):
            async with ClientSession(read, write) as session:
                await session.initialize()
                reply = await session.call_tool("pvsyst_run_simulation", dict(request))
                text = "\n".join(item.text for item in reply.content if hasattr(item, "text"))
                return reply.is_error, text

    async def _check(self, case: Case) -> None:
        base = Path(tempfile.mkdtemp(prefix="pvsyst-preflight-nolaunch-"))
        try:
            guard = base / "guardsrc"
            guard.mkdir()
            (guard / "sitecustomize.py").write_text(GUARD_SOURCE, encoding="utf-8")
            counter = base / "guard.counter"
            workspace = base / "PVsyst8.1_Data"
            for folder in ("Projects", "Results", "Models", "Meteo", "Sites"):
                (workspace / folder).mkdir(parents=True)
            (workspace / "Projects" / "Example.PRJ").write_text(
                "PVObject_=pvProject\nEnd of PVObject pvProject\n", encoding="utf-8")
            (workspace / "Projects" / "Example.VC0").write_text(
                "PVObject_=pvVCalcul\nEnd of PVObject pvVCalcul\n", encoding="utf-8")
            if case.prebuild:
                (workspace / "Results" / case.prebuild).write_bytes(b"existing output fixture\n")
            env = self._child_env(guard, workspace, counter)
            self._prove_guard_live(env, counter)

            before = {p.relative_to(workspace): p.read_bytes()
                      for p in workspace.rglob("*") if p.is_file()}

            is_error, text = await self._call(env, base, case.request)
            self.assertTrue(is_error, "%s: invalid request must be an error, got %r" % (case.name, text))
            self.assertIn(case.error, text,
                          "%s: expected preflight message %r, got %r" % (case.name, case.error, text))

            launched = hits(counter)
            self.assertEqual(launched, [],
                             "%s: invalid request launched real CLI processes %r" % (case.name, launched))

            after = {p.relative_to(workspace): p.read_bytes()
                     for p in workspace.rglob("*") if p.is_file()}
            self.assertEqual(after, before,
                             "%s: workspace files changed on an invalid request" % case.name)
        finally:
            shutil.rmtree(base, ignore_errors=True)


if __name__ == "__main__":
    unittest.main()
