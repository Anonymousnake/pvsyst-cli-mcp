"""Opt-in real-native public MCP plain-CSV (windowless) launch contract.

The permanent external acceptance gate for the Windows private non-input-desktop
launch on the bare hourly-CSV path: the product tool ``pvsyst_run_simulation`` must
complete one plain numeric CSV simulation (no PDF, no batch) from a session that
offers no interactive user desktop, and return the produced CSV while leaving the
PDF/batch fields empty.

Only observable public behavior is asserted: one ``pvsyst_run_simulation`` call, its
documented return shape, and the produced CSV file. Desktop names, window handles,
the DACL, Jobs, threads and per-handle cleanup are NOT inspected here -- that
OS-lifecycle / window-station boundary belongs to a throwaway private harness
(``windows/windowless-launch-verifier-r1``) and is never bound into this permanent
suite.

This test launches the REAL executable (no fake stub) and CONSUMES one license
execution, so it must run inside the documented non-interactive fixture session on
the acceptance host. Default is skip; it runs only when explicitly opted in.

Env (required unless noted; anything missing -> skip):
  PVSYST_CONTRACT_REAL_NATIVE=1   explicit opt-in; absent means "do not run native"
  PVSYST_CONTRACT_CLI=<path>      real installed PVsystCLI.exe
  PVSYST_CONTRACT_WORKSPACE=<dir> real PVsyst8.1_Data workspace
  PVSYST_CONTRACT_RUN_JSON=<json> the complete fixture request, e.g.
      {"project":"ROOF_SOURCE.PRJ","variant":"VC1","sfi_name":"x.sfi",
       "met_name":"y.met","start_date":"1990.01.01","end_date":"1990.01.02",
       "time_step":"hour","recompute_shading":true}
    ``csv_name`` is generated by this test and ``pdf_name`` / ``batch_*`` are
    ignored, so the request is always the plain-CSV path.

Budget: at most one run-simulation request per acceptance case (WinSta0 and the
non-interactive service station), never more; the internal license preflight is
part of that run. This phase commits the draft and runs zero requests.
"""
import asyncio
import json
import os
import sys
import uuid
from pathlib import Path
import unittest

from mcp import ClientSession
from mcp.client.stdio import StdioServerParameters, stdio_client

REPO = Path(__file__).resolve().parents[2]
_ALLOWED_INPUTS = frozenset({
    "sfi_name", "met_name", "rvt_name", "params_name", "site_name",
    "start_date", "end_date", "time_step", "report_language",
    "recompute_shading", "log_level",
})


class NativePlainCsvWindowlessE2E(unittest.TestCase):
    def setUp(self):
        if os.name != "nt":
            self.skipTest("windowless launch contract is Windows-only")
        if os.environ.get("PVSYST_CONTRACT_REAL_NATIVE") != "1":
            self.skipTest("Set PVSYST_CONTRACT_REAL_NATIVE=1 to opt into the real-native plain-CSV gate")
        cli = os.environ.get("PVSYST_CONTRACT_CLI")
        workspace = os.environ.get("PVSYST_CONTRACT_WORKSPACE")
        raw = os.environ.get("PVSYST_CONTRACT_RUN_JSON")
        if not cli or not Path(cli).is_file():
            self.skipTest("Set PVSYST_CONTRACT_CLI to a real installed PVsystCLI.exe")
        if not workspace or not Path(workspace).is_dir():
            self.skipTest("Set PVSYST_CONTRACT_WORKSPACE to a real PVsyst8.1_Data workspace")
        if not raw:
            self.skipTest("Set PVSYST_CONTRACT_RUN_JSON to the fixture project/variant request")
        try:
            spec = json.loads(raw)
        except ValueError as exc:
            self.fail("PVSYST_CONTRACT_RUN_JSON is not valid JSON: %s" % exc)
        if not isinstance(spec, dict) or not spec.get("project") or not spec.get("variant"):
            self.fail("PVSYST_CONTRACT_RUN_JSON needs at least project and variant")
        self.cli = cli
        self.workspace = workspace
        # Fixture supplies the project/variant/input files; this test owns the
        # plain-CSV shape (generated csv_name, no pdf, no batch).
        self.request = {"project": spec["project"], "variant": spec["variant"]}
        self.request.update({key: value for key, value in spec.items()
                             if key in _ALLOWED_INPUTS})

    def test_plain_csv_round_trip_without_interactive_desktop(self):
        asyncio.run(self.check())

    async def check(self):
        name = "windowless-%s" % uuid.uuid4().hex
        csv_path = Path(self.workspace) / "Results" / (name + ".csv")
        env = dict(os.environ, PVSYST_CLI=self.cli, PVSYST_WORKSPACE=self.workspace,
                   PYTHONDONTWRITEBYTECODE="1")
        env.pop("PVSYST_TOOL_GROUPS", None)
        env.pop("PVSYST_BUILTIN_COMPONENTS", None)
        params = StdioServerParameters(
            command=sys.executable, args=[str(REPO / "pvsyst_mcp_server.py")],
            cwd=str(REPO), env=env)
        try:
            async with stdio_client(params) as (read, write):
                async with ClientSession(read, write) as session:
                    await session.initialize()
                    reply = await session.call_tool("pvsyst_run_simulation",
                                                    dict(self.request, csv_name=name))
                    self.assertFalse(reply.is_error, reply.content)
                    value = json.loads("\n".join(item.text for item in reply.content
                                                 if hasattr(item, "text")))
                    # Plain-CSV external outcome: a real CSV file, and no PDF/batch.
                    self.assertIsNone(value.get("pdf"))
                    self.assertIsNone(value.get("batch_summary"))
                    self.assertIsNone(value.get("batch_runs"))
                    self.assertEqual(value.get("batch_hourly"), [])
                    produced = value.get("csv")
                    self.assertIsInstance(produced, str)
                    self.assertTrue(produced.lower().endswith(".csv"))
                    self.assertEqual(Path(produced).resolve(), csv_path.resolve())
                    self.assertTrue(csv_path.is_file() and csv_path.stat().st_size > 0)
                    seconds = value.get("seconds")
                    self.assertTrue(seconds is None
                                    or (isinstance(seconds, int) and seconds >= 0))
        finally:
            try:
                csv_path.unlink()
            except OSError:
                pass


if __name__ == "__main__":
    unittest.main()
