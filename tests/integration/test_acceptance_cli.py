"""Offline CLI tests for scripts/native_acceptance.py."""
from datetime import datetime, timedelta
import csv
import ctypes
import importlib.util
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch


REPO = Path(__file__).resolve().parents[2]
ENTRY = REPO / "scripts" / "native_acceptance.py"


class AcceptanceCLITests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory(prefix="pvsyst-acceptance-")
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        self.workspace = self.root / "fixture"
        for name in ("Projects", "Results", "Models"):
            (self.workspace / name).mkdir(parents=True)
        (self.workspace / "Projects" / "Candidate.PRJ").write_text("Fixture, not a native project")
        (self.workspace / "Projects" / "Candidate.VC0").write_text("Fixture, not a native variant")
        (self.workspace / "Models" / "columns.sfi").write_text("Fixture, never executed")
        (self.root / "equivalence.txt").write_text("Synthetic validator fixture; no Native claim")
        self.path = self.root / "case.json"
        context = {"Project": "Candidate.PRJ", "Simulation variant": "Candidate.VC0",
                   "Geographical Site": "Example.SIT", "Weather data": "Example.MET"}
        reference_context = dict(context, Project="Reference.PRJ", **{"Simulation variant": "Reference.VC1"})
        limits = {"unit": "kW", "role": "energy", "abs_tol": 0, "rel_tol": 0,
                  "total_abs_tol": 0, "total_rel_tol": 0}
        self.case = {"schema_version": 1, "case_id": "synthetic-validator", "feature": "CSV comparison",
                     "native_version": "8.1.7.49382", "workspace": "fixture",
                     "fixture_provenance": "Generated by test suite",
                     "input_equivalence": {"basis": "Same synthetic numeric rows", "evidence": "equivalence.txt"},
                     "baseline": {"csv": "baseline.csv", "producer": "native_gui", "version": "8.1.6.49278",
                                  "provenance": "Synthetic declaration, not evidence of a GUI run",
                                  "context": reference_context},
                     "period": {"start": "1990-01-01", "end": "1990-01-02"},
                     "columns": {"E_Grid": limits, "ShdElec": dict(limits, role="loss")},
                     "request": {"project": "Candidate.PRJ", "variant": "VC0", "sfi_name": "columns.sfi"},
                     "context": context}
        self.write_case()
        self.csv("baseline.csv", reference_context)
        self.csv("candidate.csv", context)

    def write_case(self):
        self.path.write_text(json.dumps(self.case), encoding="utf-8")

    def csv(self, name, context=None, *, offset=0, rows=24, unit="kW", bad_stamp=False, nonfinite=False):
        context = context or self.case["context"]
        path = self.root / name
        with path.open("w", encoding="utf-8", newline="") as stream:
            writer = csv.writer(stream, delimiter=";")
            writer.writerows((key, value, "01/01/90 00h00", "Native metadata", "")
                             for key, value in context.items())
            writer.writerow(("date", "E_Grid", "ShdElec"))
            writer.writerow(("", unit, "kW"))
            for index in range(rows):
                stamp = datetime(1990, 1, 1) + timedelta(hours=index + (1 if bad_stamp and index == 5 else 0))
                value = "nan" if nonfinite and index == 5 else 10 + index + offset
                writer.writerow((stamp.strftime("%d/%m/%y %H:%M"), value, index % 2))
        return path

    def invoke(self, *arguments):
        environment = dict(os.environ, PYTHONDONTWRITEBYTECODE="1")
        for name in tuple(environment):
            if name.startswith("PVSYST_"):
                del environment[name]
        result = subprocess.run([sys.executable, str(ENTRY), *map(str, arguments)],
                                cwd=self.root, env=environment, capture_output=True, text=True, timeout=30)
        self.assertTrue(result.stdout, result.stderr)
        return result.returncode, json.loads(result.stdout)

    def compare(self, name="candidate.csv"):
        return self.invoke("compare", self.path, "--candidate", self.root / name)

    def test_equal_numeric_rows_are_compared_not_native_consumption(self):
        before = {p: p.read_bytes() for p in self.root.rglob("*") if p.is_file()}
        code, report = self.compare()
        self.assertEqual(code, 0, report)
        self.assertEqual(report["status"], "compared")
        self.assertFalse(report["native_completed"])
        self.assertFalse(report["native_consumption_verified"])
        self.assertEqual((report["request_budget_spent"], report["cli_commands_spent"]), (0, 0))
        self.assertEqual(report["comparison"]["rows"], 24)
        self.assertEqual(report["comparison"]["columns"]["E_Grid"]["candidate_energy_kwh"], 516)
        self.assertEqual(report["comparison"]["columns"]["ShdElec"]["candidate_energy_kwh"], 12)
        self.assertEqual(report["persistence_acceptance"], "not_run")
        self.assertEqual(before, {p: p.read_bytes() for p in self.root.rglob("*") if p.is_file()})

    def test_energy_role_does_not_require_a_grid_only_column(self):
        self.case["columns"]["E_User"] = self.case["columns"].pop("E_Grid")
        self.write_case()
        for name in ("baseline.csv", "candidate.csv"):
            path = self.root / name
            path.write_text(path.read_text(encoding="utf-8").replace("E_Grid", "E_User"), encoding="utf-8")
        code, report = self.compare()
        self.assertEqual(code, 0, report)
        self.assertEqual(report["comparison"]["columns"]["E_User"]["candidate_energy_kwh"], 516)
        self.assertFalse(report["native_consumption_verified"])

    def test_sample_and_aggregate_tolerances_are_both_required(self):
        self.csv("candidate.csv", offset=0.1)
        code, report = self.compare()
        self.assertEqual(code, 1, report)
        self.assertGreater(report["comparison"]["columns"]["E_Grid"]["outside_tolerance"], 0)
        self.case["columns"]["E_Grid"].update(abs_tol=0.2, total_abs_tol=0.5)
        self.write_case()
        code, report = self.compare()
        self.assertEqual(code, 1, report)
        state = report["comparison"]["columns"]["E_Grid"]
        self.assertEqual(state["outside_tolerance"], 0)
        self.assertFalse(state["total_within_tolerance"])
        self.case["columns"]["E_Grid"]["total_abs_tol"] = 3
        self.write_case()
        code, report = self.compare()
        self.assertEqual(code, 0, report)
        self.assertFalse(report["native_consumption_verified"])

    def test_bad_coverage_units_context_and_samples_fail_closed(self):
        for options in ({"rows": 23}, {"bad_stamp": True}, {"unit": "W"}, {"nonfinite": True},
                        {"context": dict(self.case["context"], Project="Different.PRJ")}):
            with self.subTest(options=options):
                self.csv("candidate.csv", **options)
                code, report = self.compare()
                self.assertEqual(code, 1, report)
                self.assertEqual(report["status"], "failed")
                self.assertFalse(report["native_consumption_verified"])
                self.assertEqual(report["cli_commands_spent"], 0)
        code, report = self.compare("baseline.csv")
        self.assertEqual(code, 1, report)

    def test_unknown_version_duplicate_keys_and_bad_tolerances_fail_closed(self):
        self.case["native_version"] = "8.2.0.1"
        self.write_case()
        code, report = self.compare()
        self.assertEqual(code, 1, report)
        self.assertIn("Unknown native version", report["error"]["message"])
        self.case["native_version"] = "8.1.7.49382"
        self.case["columns"]["E_Grid"]["abs_tol"] = True
        self.write_case()
        code, report = self.compare()
        self.assertEqual(code, 1, report)
        self.path.write_text('{"schema_version":1,"schema_version":1}', encoding="utf-8")
        code, report = self.compare()
        self.assertEqual(code, 1, report)
        self.assertIn("Duplicate JSON field", report["error"]["message"])

    def test_invalid_reference_fails_before_any_native_command(self):
        self.csv("baseline.csv", self.case["baseline"]["context"], rows=23)
        attempt = self.root / "bad-reference"
        code, report = self.invoke("run", self.path, "--cli", sys.executable, "--attempt", attempt,
                                   "--attempt-id", "test-bad-reference", "--max-cli-commands", 3)
        self.assertEqual(code, 1, report)
        self.assertIn("coverage is incomplete", report["error"]["message"])
        self.assertEqual((report["request_budget_spent"], report["cli_commands_spent"]), (1, 0))
        self.assertFalse(list(attempt.glob("native-*-intent.json")))
        self.assertEqual(json.loads((attempt / "report.json").read_text()), report)

    def test_failed_native_precheck_spends_request_and_preserves_evidence(self):
        executable = self.root / "PVsystCLI.exe"
        executable.write_bytes(b"Not a PE executable; no version resource; must never launch")
        attempt = self.root / "attempt"
        command = ("run", self.path, "--cli", executable, "--attempt", attempt,
                   "--attempt-id", "test-no-native", "--max-cli-commands", 3)
        code, report = self.invoke(*command)
        self.assertEqual(code, 1, report)
        self.assertEqual((report["request_budget_spent"], report["cli_commands_spent"]), (1, 0))
        self.assertFalse(report["native_consumption_verified"])
        saved = (attempt / "report.json").read_bytes()
        self.assertEqual(json.loads(saved), report)
        self.assertTrue((attempt / "budget-spent.json").is_file())
        self.assertEqual((attempt / "case.json").read_bytes(), self.path.read_bytes())
        self.assertFalse(list(attempt.glob("native-*-intent.json")))
        code, repeated = self.invoke(*command)
        self.assertEqual(code, 1, repeated)
        self.assertEqual(repeated["cli_commands_spent"], 0)
        self.assertEqual((attempt / "report.json").read_bytes(), saved)

    def test_attempt_inside_source_is_rejected_without_changing_source(self):
        before = {p: p.read_bytes() for p in self.workspace.rglob("*") if p.is_file()}
        target = self.workspace / "bad-attempt"
        code, report = self.invoke("run", self.path, "--attempt", target,
                                   "--attempt-id", "test-invalid-location", "--max-cli-commands", 3)
        self.assertEqual(code, 1, report)
        self.assertEqual((report["request_budget_spent"], report["cli_commands_spent"]), (1, 0))
        self.assertFalse(target.exists())
        self.assertEqual(before, {p: p.read_bytes() for p in self.workspace.rglob("*") if p.is_file()})

    def test_cp1252_units_and_context_decode_cleanly_while_bom_corrupt_utf8_fails(self):
        self.case["context"]["Geographical Site"] = "Caf\u00e9.SIT"
        self.case["baseline"]["context"]["Geographical Site"] = "Caf\u00e9.SIT"
        self.write_case()

        def write_cp1252(name, context):
            lines = [f"{k};{v};01/01/90 00h00;Native metadata;\r\n" for k, v in context.items()]
            lines.append("date;E_Grid;ShdElec;GlobInc\r\n")
            lines.append(";kW;kW;W/m\u00b2\r\n")
            for idx in range(24):
                stamp = (datetime(1990, 1, 1) + timedelta(hours=idx)).strftime("%d/%m/%y %H:%M")
                lines.append(f"{stamp};{10 + idx};{idx % 2};500\r\n")
            (self.root / name).write_bytes("".join(lines).encode("cp1252"))

        write_cp1252("baseline.csv", self.case["baseline"]["context"])
        write_cp1252("candidate.csv", self.case["context"])
        code, report = self.compare()
        self.assertEqual(code, 0, report)
        self.assertEqual(report["status"], "compared")

        (self.root / "candidate.csv").write_bytes(b"\xef\xbb\xbf" + (self.root / "candidate.csv").read_bytes())
        code, bad = self.compare()
        self.assertEqual(code, 1, bad)
        self.assertEqual(bad["status"], "failed")

    def test_workspace_bytes_accepts_short_paths_and_rejects_links_and_junctions(self):
        spec = importlib.util.spec_from_file_location("native_acceptance", ENTRY)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)

        long_dir = self.root / "very_long_acceptance_fixture_directory"
        (long_dir / "Projects").mkdir(parents=True)
        (long_dir / "Projects" / "Example.PRJ").write_bytes(b"fixture")
        expected = {Path("Projects/Example.PRJ"): b"fixture"}
        self.assertEqual(mod.workspace_bytes(long_dir), expected)
        if os.name == "nt":
            buf = ctypes.create_unicode_buffer(1024)
            if ctypes.windll.kernel32.GetShortPathNameW(str(long_dir), buf, len(buf)):
                self.assertEqual(mod.workspace_bytes(Path(buf.value)), expected)
            outside = self.root / "outside_target"
            outside.mkdir()
            junction = long_dir / "linked_dir"
            created = subprocess.run(["cmd", "/c", "mklink", "/J", str(junction), str(outside)],
                                     capture_output=True, text=True)
            if created.returncode == 0:
                try:
                    with self.assertRaisesRegex(ValueError, "links and junctions"):
                        mod.workspace_bytes(long_dir)
                finally:
                    junction.rmdir()
        with patch.object(Path, "is_symlink", side_effect=lambda self=None: True):
            with self.assertRaisesRegex(ValueError, "links and junctions"):
                mod.workspace_bytes(long_dir)

    def test_run_mode_validates_cli_flags_before_creating_attempt_dir(self):
        invalid_invocations = (
            ("candidate_in_run", ("--cli", sys.executable, "--max-cli-commands", 3, "--candidate", self.root / "candidate.csv")),
            ("missing_cli", ("--max-cli-commands", 3)),
            ("nonexistent_cli", ("--cli", self.root / "missing.exe", "--max-cli-commands", 3)),
            ("directory_cli", ("--cli", self.workspace, "--max-cli-commands", 3)),
            ("missing_budget", ("--cli", sys.executable)),
            ("zero_budget", ("--cli", sys.executable, "--max-cli-commands", 0)),
            ("excess_budget", ("--cli", sys.executable, "--max-cli-commands", 4)),
        )
        for index, (label, extra_args) in enumerate(invalid_invocations):
            attempt = self.root / f"precheck-{index}"
            with self.subTest(case=label):
                code, report = self.invoke("run", self.path, "--attempt", attempt,
                                           "--attempt-id", f"id-{index}", *extra_args)
                self.assertEqual(code, 1, report)
                self.assertEqual(report["status"], "failed")
                self.assertFalse(attempt.exists(), f"{label} should not create attempt directory")


if __name__ == "__main__":
    unittest.main()
