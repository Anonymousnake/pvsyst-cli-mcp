class PackageEntrypointTests(unittest.TestCase):
    async def _capture(self, command, source_checkout=False):
        with tempfile.TemporaryDirectory(prefix="pvsyst-entry-") as temporary:
            root = Path(temporary) / "PVsyst8.1_Data"
            root.mkdir()
            binary = Path(temporary) / "PVsystCLI.exe"
            binary.write_bytes(b"Public entrypoint must never execute native software")
            env = dict(os.environ, PVSYST_WORKSPACE=str(root), PVSYST_CLI=str(binary), PYTHONDONTWRITEBYTECODE="1")
            env.pop("PYTHONPATH", None)
            if source_checkout:
                env["PYTHONPATH"] = str(REPO / "src")
            parameters = StdioServerParameters(command=command[0], args=command[1:], cwd=temporary, env=env)
            async with stdio_client(parameters) as (read, write):
                async with ClientSession(read, write) as session:
                    init = await session.initialize()
                    self.assertTrue(init.instructions and "pvsyst_simulate_design" in init.instructions)
                    prompts = {item.name for item in (await session.list_prompts()).prompts}
                    self.assertEqual(prompts, {
                        "design_fixed_or_utility_pv", "design_rooftop_3d_pv",
                        "design_pv_with_storage", "diagnose_and_optimize_simulation",
                    })
                    resources = {str(item.uri) for item in (await session.list_resources()).resources}
                    self.assertEqual(resources, {"pvsyst://guide/workflows", "pvsyst://guide/variables"})
                    tools = (await session.list_tools()).tools
                    names = {tool.name for tool in tools}
                    self.assertEqual(len(names), 39)
                    self.assertTrue({"pvsyst_capabilities", "pvsyst_license_info", "pvsyst_suggest_sizing",
                                     "pvsyst_diagnose_results", "pvsyst_project_handoff",
                                     "pvsyst_export_engineering_delivery",
                                     "pvsyst_run_engineering_task", "pvsyst_simulate_design",
                                     "pvsyst_run_house_task", "pvsyst_create_native_load_variant"}.issubset(names))
                    self.assertTrue({"pvsyst_license_activate", "pvsyst_prepare_block_project",
                                     "pvsyst_clone_project", "pvsyst_simulate_template"}.isdisjoint(names))
                    reply = await session.call_tool("pvsyst_run_engineering_task", {
                        "spec": {
                            "source_project": "Missing.PRJ", "source_variant": "VC0",
                            "new_project": "Work.PRJ", "new_variant": "VC1",
                            "objective": "Public entrypoint", "year": 2024,
                            "nominal_dc_power_kw": 10.0, "power_source": "Declared fixture",
                            "changes": {},
                        }})
                    self.assertFalse(reply.is_error, reply.content)
                    value = json.loads("\n".join(item.text for item in reply.content if hasattr(item, "text")))
                    self.assertEqual(value["status"], "blocked")
                    self.assertFalse(value["native_consumption_verified"])
                    unknown = await session.call_tool("pvsyst_run_engineering_task", {"spec": {}, "unexpected": True})
                    self.assertTrue(unknown.is_error)
                    self.assertIn("Unknown argument", "\n".join(item.text for item in unknown.content if hasattr(item, "text")))
            self.assertEqual(list(root.iterdir()), [])
            return {"tools": sorted([tool.model_dump(mode="json", exclude_none=True) for tool in tools], key=lambda item: item["name"]),
                    "brief": value}

    def test_checkout_module_and_legacy_launch(self):
        async def check():
            module, legacy = await asyncio.gather(
                self._capture([sys.executable, "-m", "pvsyst_auto"], True),
                self._capture([sys.executable, str(REPO / "pvsyst_mcp_server.py")]),
            )
            self.assertEqual(module, legacy)
        asyncio.run(check())

    def test_installed_console_and_module_launch(self):
        python = os.environ.get("PVSYST_PACKAGE_INSTALLED_PYTHON")
        console = os.environ.get("PVSYST_PACKAGE_INSTALLED_CONSOLE")
        if not python or not console:
            self.skipTest("Provide explicit wheel-installed Python and console executable")
        self.assertTrue(Path(python).is_file())
        self.assertTrue(Path(console).is_file())

        async def check():
            module, entry, source = await asyncio.gather(
                self._capture([python, "-m", "pvsyst_auto"]),
                self._capture([console]),
                self._capture([sys.executable, "-m", "pvsyst_auto"], True),
            )
            self.assertEqual(module, entry)
            self.assertEqual(source, entry)
        asyncio.run(check())

    def test_run_tests_prepends_src_unless_installed_flag_set(self):
        spec = importlib.util.spec_from_file_location("run_tests_script", REPO / "scripts" / "run_tests.py")
        runner_mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(runner_mod)
        src_str = str(REPO / "src")
        ok_result = MagicMock(wasSuccessful=MagicMock(return_value=True), testsRun=1)
        original_path = list(sys.path)
        try:
            sys.path[:] = [p for p in original_path if p != src_str]
            with patch.dict(os.environ, {}, clear=False), \
                    patch.object(unittest.TestLoader, "discover", return_value=unittest.TestSuite()), \
                    patch.object(unittest.TextTestRunner, "run", return_value=ok_result):
                os.environ.pop("PVSYST_TEST_INSTALLED", None)
                self.assertEqual(runner_mod.main(["--suite", "core"]), 0)
                self.assertEqual(sys.path[0], src_str)

            sys.path[:] = [p for p in original_path if p != src_str]
            with patch.dict(os.environ, {"PVSYST_TEST_INSTALLED": "1"}), \
                    patch.object(unittest.TestLoader, "discover", return_value=unittest.TestSuite()), \
                    patch.object(unittest.TextTestRunner, "run", return_value=ok_result):
                self.assertEqual(runner_mod.main(["--suite", "core"]), 0)
                self.assertNotIn(src_str, sys.path)
        finally:
            sys.path[:] = original_path


class ToolGroupsTests(unittest.TestCase):
    def test_explicit_groups_preserve_default_and_strict_calls(self):
        asyncio.run(self._check())

    def test_documented_tool_surface_matches_registration(self):
        reference = (REPO / "docs" / "tool-reference.md").read_text(encoding="utf-8")
        start = reference.index("## Tools by workflow group")
        end = reference.find("\n## ", start + 1)
        section = reference[start:end if end >= 0 else None]
        all_names = tool_names_for_groups(resolve_tool_groups("all"))
        self.assertEqual(set(re.findall(r"\bpvsyst_\w+\b", section)), set(all_names))
        headings = re.finditer(
            r"^### .+? \(`(?P<group>\w+)`, (?:default|opt-in): (?P<count>\d+)\)$",
            section, re.MULTILINE)
        heading_count = 0
        for heading in headings:
            heading_count += 1
            expected = len(tool_names_for_groups((heading["group"],)))
            self.assertEqual(int(heading["count"]), expected, heading.group(0))
        self.assertGreater(heading_count, 0)

        default_count = len(tool_names_for_groups(resolve_tool_groups(None)))
        counts = {default_count, len(all_names)}
        def documented_counts(text):
            values = []
            for fragment in re.findall(r"\*\*([^*]+)\*\*", text):
                if "tool" not in fragment.lower() and "工具" not in fragment:
                    continue
                values.extend(int(value) for value in re.findall(
                    r"(?<!\w)(\d+)(?=[^0-9]*(?:\btools?\b|工具))", fragment, re.I))
            return values

        for path in (REPO / "README.md", REPO / "README.zh-CN.md"):
            values = documented_counts(path.read_text(encoding="utf-8"))
            self.assertTrue(values, path)
            self.assertTrue(set(values) <= counts, (path, values))
            self.assertIn(default_count, values, path)
            self.assertIn(len(all_names), values, path)
        intro = documented_counts(reference[:start])
        self.assertTrue(intro)
        self.assertTrue(set(intro) <= counts, intro)

    async def _check(self):
        directory = Path(tempfile.mkdtemp(prefix="pvsyst-groups-"))
        try:
            workspace = directory / "PVsyst8.1_Data"
            workspace.mkdir()
            binary = directory / "PVsystCLI.exe"
            binary.write_bytes(b"Tool discovery must never execute native software")
            env = dict(os.environ, PVSYST_WORKSPACE=str(workspace), PVSYST_CLI=str(binary),
                       PYTHONPATH=str(REPO / "src"), PYTHONDONTWRITEBYTECODE="1")
            env.pop("PVSYST_TOOL_GROUPS", None)

            async def capture(groups, module=False):
                current = dict(env)
                if groups is not None:
                    current["PVSYST_TOOL_GROUPS"] = groups
                args = ["-m", "pvsyst_auto"] if module else [str(REPO / "pvsyst_mcp_server.py")]
                parameters = StdioServerParameters(command=sys.executable, args=args, cwd=str(directory), env=current)
                async with stdio_client(parameters) as (read, write):
                    async with ClientSession(read, write) as session:
                        await session.initialize()
                        tools = sorted([item.model_dump(mode="json", by_alias=True, exclude_none=True)
                                        for item in (await session.list_tools()).tools], key=lambda item: item["name"])
                        if groups is not None:
                            for gone in ("pvsyst_clone_project", "pvsyst_open_native_project",
                                         "pvsyst_simulate_template", "pvsyst_create_peak_shaving_variant",
                                         "pvsyst_create_load_variant"):
                                reply = await session.call_tool(gone, {})
                                self.assertTrue(reply.is_error)
                                self.assertRegex("\n".join(i.text for i in reply.content if hasattr(i, "text")).lower(),
                                                 r"unknown tool|not found|not registered")
                        if groups is None:
                            reply = await session.call_tool("pvsyst_update_variant_parameters", {
                                "project": "SOURCE.PRJ", "variant": "VC0", "expected_sha256": "0" * 64, "dryrun": True})
                            self.assertTrue(reply.is_error)
                            self.assertIn("Unknown argument(s) for pvsyst_update_variant_parameters: dryrun",
                                          "\n".join(i.text for i in reply.content if hasattr(i, "text")))
                return tools

            default_tools, full, selected, expert_only, admin_only = await asyncio.gather(
                capture(None),
                capture("all"),
                capture("setup, engineering,results", module=True),
                capture("expert"),
                capture("admin"),
            )
            default_names = {item["name"] for item in default_tools}
            full_names = {item["name"] for item in full}
            self.assertEqual(len(default_names), 39)
            self.assertEqual(len(full_names), 68)
            self.assertTrue({"pvsyst_license_info", "pvsyst_suggest_sizing", "pvsyst_diagnose_results",
                             "pvsyst_project_handoff", "pvsyst_export_engineering_delivery"}.issubset(default_names))
            self.assertTrue({"pvsyst_license_activate", "pvsyst_prepare_block_project"}.isdisjoint(default_names))
            self.assertTrue({"pvsyst_license_activate", "pvsyst_prepare_block_project"}.issubset(full_names))
            self.assertEqual({item["name"] for item in admin_only},
                             {"pvsyst_license_activate", "pvsyst_license_deactivate",
                              "pvsyst_license_sync", "pvsyst_export_logs"})
            self.assertEqual(len(expert_only), 25)
            self.assertEqual(default_names | {i["name"] for i in expert_only} | {i["name"] for i in admin_only}, full_names)
            expected = [item for item in full if item["description"].split("]", 1)[0][1:]
                        in {"Setup & License", "Engineering", "Results"}]
            self.assertEqual(selected, expected)
            self.assertEqual(list(workspace.iterdir()), [])
            invalid_values = ("", "engineering,", "unknown", "results,results", "all,setup")
            processes = await asyncio.gather(*(
                asyncio.to_thread(
                    subprocess.run,
                    [sys.executable, "-m", "pvsyst_auto"],
                    cwd=directory,
                    env={**env, "PVSYST_TOOL_GROUPS": invalid},
                    stdin=subprocess.DEVNULL,
                    capture_output=True,
                    text=True,
                    timeout=30,
                )
                for invalid in invalid_values
            ))
            for index, process in enumerate(processes):
                self.assertNotEqual(process.returncode, 0, index)
                self.assertIn("PVSYST_TOOL_GROUPS requires", process.stdout + process.stderr)
        finally:
            shutil.rmtree(directory, ignore_errors=True)


class SimulationPreflightNoLaunchTests(unittest.TestCase):
    def test_invalid_requests_spawn_zero_cli_and_write_nothing(self):
        asyncio.run(self._check())

    async def _check(self):
        directory = Path(tempfile.mkdtemp(prefix="pvsyst-preflight-guard-"))
        try:
            guard = directory / "guard"
            guard.mkdir()
            (guard / "sitecustomize.py").write_text(GUARD_SOURCE, encoding="utf-8")
            workspace = directory / "ws"
            for name in ("Projects", "Results"):
                (workspace / name).mkdir(parents=True)
            (workspace / "Projects" / "Example.PRJ").write_text("PVObject_=pvProject\nEnd of PVObject pvProject\n", encoding="utf-8")
            (workspace / "Projects" / "Example.VC0").write_text("PVObject_=pvVCalcul\nEnd of PVObject pvVCalcul\n", encoding="utf-8")
            (workspace / "Results" / "existing.csv").write_text("date;E_Grid\n", encoding="utf-8")
            counter = directory / "launches.txt"
            env = dict(os.environ, PVSYST_CLI=sys.executable, PVSYST_WORKSPACE=str(workspace),
                       PVSYST_GUARD_COUNTER=str(counter), PYTHONPATH=os.pathsep.join([str(guard), str(REPO / "src")]),
                       PYTHONDONTWRITEBYTECODE="1")
            for k in ("PVSYST_TOOL_GROUPS", "PVSYST_BUILTIN_COMPONENTS"):
                env.pop(k, None)

            probe_script = guard / "lic-info"
            probe_script.write_text("pass\n", encoding="utf-8")
            probe = subprocess.run([sys.executable, str(probe_script)],
                                   env=env, capture_output=True, check=True)
            self.assertEqual(counter.read_text(encoding="utf-8").splitlines(), ["lic-info"], probe.stderr)
            counter.unlink()

            params = StdioServerParameters(command=sys.executable, args=[str(REPO / "pvsyst_mcp_server.py")], cwd=str(directory), env=env)
            async with stdio_client(params) as (read, write):
                async with ClientSession(read, write) as session:
                    await session.initialize()
                    for name, req, message, _ in PREFLIGHT_CASES:
                        with self.subTest(case=name):
                            reply = await session.call_tool("pvsyst_run_simulation", req)
                            self.assertTrue(reply.is_error, reply.content)
                            text = "\n".join(i.text for i in reply.content if hasattr(i, "text"))
                            self.assertIn(message, text)
            self.assertFalse(counter.exists(), "Pure invalid preflight launched PVsystCLI!")
        finally:
            shutil.rmtree(directory, ignore_errors=True)


