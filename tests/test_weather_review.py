    """The value-only inspector's public contract: dates, coverage, units and monthly energy."""

    def report(self):
        return inspect_weather_values(self.root / "Meteo" / self.csv_name, self.year)

    def test_complete_year_coverage_and_labels(self):
        report = self.report()
        self.assertIs(report["valid"], True)
        self.assertEqual(report["rows"], year_hours(self.year))
        self.assertEqual(report["expected_rows"], year_hours(self.year))
        self.assertEqual(report["expected_year"], self.year)
        self.assertTrue(report["raw_hourly_coverage_complete"])
        self.assertEqual(report["first"], "2024-01-01 00:00:00")
        self.assertEqual(report["last"], "2024-12-31 23:00:00")
        self.assertEqual(report["missing_hours"], 0)
        self.assertEqual(report["unexpected_timestamps"], 0)
        self.assertEqual(report["duplicate_timestamps"], 0)
        self.assertEqual(report["nonzero_minute_records"], 0)
        self.assertEqual(report["ignored_columns"], [])
        self.assertEqual(report["format"], "pvsyst_standard_hourly")
        self.assertEqual(report["delimiter"], ";")

    def test_units_and_metadata_are_reported(self):
        report = self.report()
        self.assertEqual(report["units"]["GHI"], "W/m2")
        self.assertEqual(report["units"]["DHI"], "W/m2")
        self.assertEqual(report["units"]["Tamb"], "deg.C")
        self.assertEqual(report["metadata"]["#Time step"], "Hour")
        self.assertEqual(report["metadata"]["#Year"], "2024")
        self.assertEqual(report["metadata"]["#Time Zone"], "8")

    def test_monthly_values_follow_the_fixture_diurnal_shape(self):
        report = self.report()
        self.assertEqual(len(report["months"]), 12)
        february = report["months"][1]
        self.assertEqual(february["month"], 2)
        self.assertEqual(february["rows"], 29 * 24)     # 2024 is a leap year
        self.assertEqual(february["GHI"]["finite_samples"], 29 * 24)
        # 8 daylight hours at 100 W/m2 per day: 0.8 kWh/m2/day over 29 days.
        self.assertAlmostEqual(february["GHI"]["observed_kwh_m2"], 23.2, places=6)
        annual = sum(month["GHI"]["observed_kwh_m2"] for month in report["months"])
        self.assertAlmostEqual(annual, 366 * 0.8, places=6)   # 292.8 kWh/m2
        self.assertEqual(report["months"][0]["Tamb"]["finite_samples"], 31 * 24)

    def test_a_gap_is_reported_with_examples(self):
        drop = datetime(self.year, 6, 1, 12)
        self.write_csv(rows=csv_rows(self.year, drop=drop))
        report = self.report()
        self.assertFalse(report["raw_hourly_coverage_complete"])
        self.assertEqual(report["missing_hours"], 1)
        self.assertIn("2024-06-01 12:00:00", report["missing_examples"])
        self.assertIs(report["valid"], False)


