class ReviewFixture(unittest.TestCase):
    """Builds a temporary workspace holding CSV, native result and provider evidence."""

    year = 2024

    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.root = Path(self.temporary.name)
        for folder in ("Meteo", "Results", "Sites"):
            (self.root / folder).mkdir()
        self.csv_name = "fixture_weather.csv"
        self.native_name = "fixture_native.csv"
        self.rows = csv_rows(self.year)
        self.write_csv()
        self.write_native()
        self.write_provider()

    def tearDown(self):
        self.temporary.cleanup()

    # -- writers ---------------------------------------------------------
    def write_csv(self, *, rows=None, extra_metadata=(), units=None, name=None):
        rows = self.rows if rows is None else rows
        (self.root / "Meteo" / (name or self.csv_name)).write_text(
            weather_csv_text(self.year, rows, extra_metadata=extra_metadata, units=units),
            encoding="utf-8-sig")

    def write_native(self, *, rows=None, units=("W/m\u00b2", "W/m\u00b2", "\u00b0C"),
                     shift_hours=0, glob_delta=0.0, name=None, context=True,
                     sit="FIXTURE.SIT", met="FIXTURE.MET"):
        rows = self.rows if rows is None else rows
        (self.root / "Results" / (name or self.native_name)).write_text(
            native_csv_text(rows, units=units, shift_hours=shift_hours, glob_delta=glob_delta,
                            sit=sit, met=met, context=context),
            encoding="utf-8-sig")

    def write_provider(self, *, payload=None, manifest=None, raw_name="fixture_raw.json",
                       manifest_name="fixture_acquisition.json"):
        payload = provider_payload(self.year) if payload is None else payload
        manifest = acquisition_manifest(self.year, raw_name=raw_name) if manifest is None else manifest
        (self.root / "Meteo" / raw_name).write_text(json.dumps(payload), encoding="utf-8")
        (self.root / "Results" / manifest_name).write_text(json.dumps(manifest), encoding="utf-8")
        return manifest_name

    def review(self, **overrides):
        arguments = {"csv_name": self.csv_name, "native_csv_name": self.native_name,
                     "year": self.year}
        arguments.update(overrides)
        return review_weather(self.root, **arguments)


