"""Offline contract tests for the read-only weather review backend.

Every fixture here is generated by this file: no real run, no network, no hashing and no
CLI. The assertions target only the public surface (``review_weather``, the two inspectors,
``compare_native_weather``) plus the documented report keys, so the tests do not bind to
private helpers. The provider stub is built independently from the published label rules
(local standard interval-start rows, radiation at the UTC interval END, Tamb as the mean of
the two bounding instants).
"""
